"""
Generate the force-field model tables of the user guide from the TOML database.

Writes two reStructuredText fragments included by ``user_guide/ff_database.rst``:

- ``user_guide/_generated/ff_models.inc``: one row per model (key, name,
  reference, description), grouped by category;
- ``user_guide/_generated/ff_mixing.inc``: the mixing rule of each model.

Run by ``docs/conf.py`` at every build, so a new TOML file shows up without
editing the documentation. The ``.inc`` suffix keeps Sphinx from building the
fragments as pages of their own.
"""

import tomllib
from pathlib import Path

DOCS = Path(__file__).resolve().parent.parent
DB_DIR = DOCS.parent / "cemd" / "forcefield" / "db"
OUT_DIR = DOCS / "user_guide" / "_generated"

CATEGORIES = {
    "minerals": "Cement phases, clays, silica and glasses",
    "carbonates": "Carbonates",
    "ions": "Ions",
    "water": "Water models",
}
MIXING = {
    "arithmetic": "arithmetic (Lorentz-Berthelot)",
    "geometric": "geometric",
    "none": "none (pair-specific terms)",
}

# Force fields read from their original files, not from TOML
EXTRA_ROWS = [
    (
        "``iff_charmm`` / ``iff_cvff``",
        "IFF v1.5 (CHARMM .prm / CVFF .frc)",
        "10.1021/la3038846",
        "Original INTERFACE force field files",
    ),
    ("``gromos``", "GROMOS 54A7 (ATB)", "", "Organic molecules (moltemplate .lt)"),
]


def load_models() -> list[tuple[str, dict]]:
    models = []
    for path in sorted(DB_DIR.glob("*.toml")):
        with open(path, "rb") as f:
            models.append((path.stem, tomllib.load(f).get("model", {})))
    order = list(CATEGORIES)
    return sorted(
        models,
        key=lambda m: (
            order.index(m[1].get("category"))
            if m[1].get("category") in order
            else len(order),
            m[0],
        ),
    )


def doi_link(ref: str) -> str:
    if not ref:
        return "—"
    doi = ref.split("doi.org/")[-1]
    return f"`{doi} <https://doi.org/{doi}>`_"


def list_table(widths: str, header: list[str], rows: list[list[str]]) -> list[str]:
    lines = [
        ".. list-table::",
        "   :header-rows: 1",
        f"   :widths: {widths}",
        "",
    ]
    for row in [header, *rows]:
        lines.append(f"   * - {row[0]}")
        lines.extend(f"     - {cell}" for cell in row[1:])
    return lines + [""]


def models_table(models: list[tuple[str, dict]]) -> str:
    lines = [
        ".. This file is generated by docs/_scripts/ff_tables.py; do not edit.",
        "",
    ]
    for category, title in CATEGORIES.items():
        rows = [
            [
                f"``{key}``",
                m.get("name", key),
                doi_link(m.get("ref", "")),
                m.get("description", ""),
            ]
            for key, m in models
            if m.get("category") == category
        ]
        if not rows:
            continue
        lines += [f"**{title}**", ""]
        lines += list_table(
            "15 18 22 45", ["Key", "Model", "Reference", "Description"], rows
        )
    other = [
        [
            f"``{key}``",
            m.get("name", key),
            doi_link(m.get("ref", "")),
            m.get("description", ""),
        ]
        for key, m in models
        if m.get("category") not in CATEGORIES
    ]
    other += [[k, n, doi_link(d), desc] for k, n, d, desc in EXTRA_ROWS]
    lines += ["**Other force-field files**", ""]
    lines += list_table(
        "15 18 22 45", ["Key", "Model", "Reference", "Description"], other
    )
    return "\n".join(lines)


def mixing_table(models: list[tuple[str, dict]]) -> str:
    rows = [
        [
            f"``{key}``",
            MIXING.get(m.get("mixing", ""), m.get("mixing", "") or "not specified"),
            m.get("mixing_note", ""),
        ]
        for key, m in models
    ]
    lines = [
        ".. This file is generated by docs/_scripts/ff_tables.py; do not edit.",
        "",
    ]
    lines += list_table("20 25 55", ["Model", "Rule", "Note"], rows)
    return "\n".join(lines)


def main() -> None:
    models = load_models()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "ff_models.inc").write_text(models_table(models), encoding="utf-8")
    (OUT_DIR / "ff_mixing.inc").write_text(mixing_table(models), encoding="utf-8")
    print(f"Generated force-field tables for {len(models)} models in {OUT_DIR}")


if __name__ == "__main__":
    main()
